/*****************************************************************************
 ** 函数声明  (CAN1通信核心接口)
****************************************************************************/
// 发送
uint8_t CAN1_SendData(uint32_t type, uint32_t ID, uint8_t *msgData, uint8_t num);  // 数据发送：帧格式、帧ID、数据地址、字节数
// 筛选器配置
void    CAN1_FilterInit(void);                                                     // CAN1筛选器配置、使能CAN1接收中断
// 接收
uint8_t  CAN1_GetRxNum(void);                                                      // 获取最后一帧接收的字节数（0=无新数据）
uint8_t *CAN1_GetRxData(void);                                                     // 获取最后一帧接收的数据缓冲区地址
void     CAN1_ClearRx(void);                                                       // 清除接收标志（重置接收字节数为0）
CAN_RxHeaderTypeDef CAN1_GetRxHeader(void);                                        // 获取最后一帧接收的报文头部信息


#endif

